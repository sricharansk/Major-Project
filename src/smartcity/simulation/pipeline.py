"""Scenario preparation, DOT->SUMO mapping, demand declaration and paired controller comparisons."""

from __future__ import annotations

import csv
import math
import re

import numpy as np

from smartcity import settings
from smartcity.simulation import sumo_runner as sr
from smartcity.utils import read_json, sha256_file, write_json

SIM = settings.ROOT / "simulation"
CFG_NAME = "west_st_corridor"


def _scfg() -> dict:
    return settings.load("simulation").get("scenario", {})


def prepare() -> dict:
    """netconvert (static + actuated), TLS inventory, corridor detection, mapping, declared demand."""
    import sumolib

    sc = _scfg()
    osm = settings.path("raw") / "osm" / f"{sc['osm_name']}.osm"
    if not osm.exists():
        raise SystemExit(f"NOT_RUN: missing OSM extract {osm}")
    nets = SIM / "networks"
    nets.mkdir(parents=True, exist_ok=True)
    static = sr.netconvert(osm, nets / f"{CFG_NAME}.static.net.xml", "static")
    actuated = sr.netconvert(osm, nets / f"{CFG_NAME}.actuated.net.xml", "actuated")
    net = sumolib.net.readNet(str(static), withPrograms=True)
    pat = re.compile(sc["corridor_name_regex"], re.I)
    corridor = [e for e in net.getEdges() if e.getName() and pat.search(e.getName()) and e.allows("passenger")]
    # split directions by edge heading
    def heading(e):
        (x1, y1), (x2, y2) = e.getShape()[0], e.getShape()[-1]
        return (math.degrees(math.atan2(x2 - x1, y2 - y1)) + 360) % 360
    nb = [e for e in corridor if heading(e) < 90 or heading(e) > 270]   # northbound-ish
    sb = [e for e in corridor if 90 <= heading(e) <= 270]
    inv = sr.tls_inventory(static)
    corridor_ids = {e.getID() for e in corridor}
    corr_tls = {t: v for t, v in inv.items() if corridor_ids & set(v["controlled_edges"])}
    # for each corridor TLS, the green phase serving the corridor = phase with most G on corridor links
    tls_obj = {t.getID(): t for t in net.getTrafficLights()}
    corridor_phase = {}
    for tid, v in corr_tls.items():
        conns = tls_obj[tid].getConnections()
        idx_corr = [c[2] for c in conns if c[0].getEdge().getID() in corridor_ids]
        best, best_n = None, -1
        for ph in v["phases"]:
            if not ph["green"]:
                continue
            n = sum(1 for i in idx_corr if i < len(ph["state"]) and ph["state"][i] in "Gg")
            if n > best_n:
                best, best_n = ph["index"], n
        if best is not None:
            corridor_phase[tid] = best
    # entry/exit edges
    def chain_ends(edges):
        ids = {e.getID() for e in edges}
        starts = [e for e in edges if not any(i.getID() in ids for i in e.getIncoming())]
        ends = [e for e in edges if not any(o.getID() in ids for o in e.getOutgoing())]
        return starts, ends
    nb_s, nb_e = chain_ends(nb)
    sb_s, sb_e = chain_ends(sb)
    # side streets: non-corridor passenger edges entering corridor TLS junctions
    side_in = set()
    for tid, v in corr_tls.items():
        for eid in v["controlled_edges"]:
            if eid not in corridor_ids:
                side_in.add(eid)
    mapping = map_dot_links(net, corridor_ids)
    demand = declare_demand()
    meta = {"network": {"static": str(static.relative_to(settings.ROOT)), "actuated": str(actuated.relative_to(settings.ROOT)),
                        "static_sha256": sha256_file(static), "actuated_sha256": sha256_file(actuated),
                        "osm_sha256": sha256_file(osm), "osm_file": str(osm.relative_to(settings.ROOT)),
                        "signal_programs": "generated by netconvert --tls.guess-signals (NOT observed NYC timing plans)"},
            "corridor": {"name_regex": sc["corridor_name_regex"], "n_edges": len(corridor), "northbound": [e.getID() for e in nb],
                         "southbound": [e.getID() for e in sb],
                         "nb_entries": [e.getID() for e in nb_s], "nb_exits": [e.getID() for e in nb_e],
                         "sb_entries": [e.getID() for e in sb_s], "sb_exits": [e.getID() for e in sb_e]},
            "tls_corridor": list(corr_tls), "corridor_phase": corridor_phase, "side_entry_edges": sorted(side_in),
            "tls_inventory": corr_tls, "demand": demand, "mapping_summary": mapping["summary"]}
    write_json(SIM / "scenarios" / "prepared.json", meta)
    return meta


def map_dot_links(net, corridor_ids: set) -> dict:
    """Geometry/direction match of DOT links to corridor SUMO edges -> simulation/mappings/dot_to_sumo.csv."""
    geoms = read_json(settings.path("processed") / "link_geometries.json") if (settings.path("processed") / "link_geometries.json").exists() else {}
    graph = read_json(settings.path("processed") / "graph.json") if (settings.path("processed") / "graph.json").exists() else {"nodes": []}
    names = {n["link_id"]: n.get("link_name") for n in graph["nodes"]}
    rows = []
    for lid, pts in geoms.items():
        if len(pts) < 2:
            continue
        xy = [net.convertLonLat2XY(lon, lat) for lat, lon in pts]
        near_hits, dir_hits, matched = 0, 0, {}
        for i in range(len(xy) - 1):
            x, y = xy[i]
            b = (math.degrees(math.atan2(xy[i + 1][0] - x, xy[i + 1][1] - y)) + 360) % 360
            cands = net.getNeighboringEdges(x, y, 30)
            cands = [(e, d) for e, d in cands if e.getID() in corridor_ids]
            if not cands:
                continue
            near_hits += 1
            e, _ = min(cands, key=lambda t: t[1])
            sh = e.getShape()
            eb = (math.degrees(math.atan2(sh[-1][0] - sh[0][0], sh[-1][1] - sh[0][1])) + 360) % 360
            diff = min(abs(eb - b) % 360, 360 - abs(eb - b) % 360)
            if diff < 45:
                dir_hits += 1
                matched[e.getID()] = matched.get(e.getID(), 0) + 1
        nseg = len(xy) - 1
        overlap = near_hits / nseg
        dmatch = dir_hits / max(near_hits, 1)
        if near_hits == 0:
            continue
        conf = "high" if overlap >= 0.6 and dmatch >= 0.8 else ("medium" if overlap >= 0.3 and dmatch >= 0.6 else "low")
        rows.append({"dot_link_id": lid, "dot_link_name": names.get(lid), "sumo_edge_id": ";".join(sorted(matched, key=matched.get, reverse=True)[:8]),
                     "direction_match": round(dmatch, 3), "geometry_overlap": round(overlap, 3),
                     "mapping_confidence": conf,
                     "review_status": "auto_checked_reviewed_by_claude_not_human" if conf == "high" else "rejected_low_overlap",
                     "signal_relevance": "corridor_signalized_arterial" if conf == "high" else "none"})
    p = SIM / "mappings" / "dot_to_sumo.csv"
    p.parent.mkdir(parents=True, exist_ok=True)
    with open(p, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["dot_link_id", "dot_link_name", "sumo_edge_id", "direction_match",
                                           "geometry_overlap", "mapping_confidence", "review_status", "signal_relevance"])
        w.writeheader()
        w.writerows(rows)
    return {"rows": rows, "summary": {"candidates": len(rows), "high": sum(r["mapping_confidence"] == "high" for r in rows)}}


def declare_demand() -> dict:
    """Corridor demand from NYC ATR counts on the corridor street (if present); otherwise declared values."""
    from smartcity.preprocessing.raw import read_socrata
    import polars as pl

    sc = _scfg()
    out = {"source": None, "main_veh_per_hour_per_direction": sc["fallback_main_vph"],
           "side_veh_per_hour_per_approach": sc["side_vph_assumption"],
           "assumptions": ["side-street volumes are declared assumptions (no matched counts)",
                           "routes: SUMO shortest path between entry and exit edges; no turning-ratio calibration"]}
    try:
        v = read_socrata("volume")
    except Exception:
        v = None
    if v is not None and not v.is_empty() and "street" in v.columns:
        pat = sc["atr_street_regex"]
        sel = v.filter(pl.col("street").str.contains(f"(?i){pat}"))
        if sel.height:
            sel = sel.with_columns(pl.col("vol").cast(pl.Float64, strict=False), pl.col("hh").cast(pl.Int32, strict=False))
            hourly = (sel.group_by(["requestid", "segmentid", "direction", "yr", "m", "d", "hh"]).agg(pl.col("vol").sum())
                      .filter(pl.col("hh").is_between(16, 18)))
            if hourly.height:
                by_dir = hourly.group_by("direction").agg(pl.col("vol").median().alias("median_pm_peak_vph"),
                                                          pl.len().alias("n_hours"))
                med = float(by_dir["median_pm_peak_vph"].median())
                out.update(source=f"NYC ATR counts 7ym2-wayt, street~/{pat}/, 16-19h hourly medians",
                           main_veh_per_hour_per_direction=round(med, 0),
                           atr_by_direction=by_dir.to_dicts(), atr_rows=sel.height,
                           atr_years=sorted(set(sel["yr"].to_list())))
    return out


def build_routes(meta: dict, scenario: dict) -> str:

    cfg = settings.load("simulation")["simulation"]
    d = meta["demand"]
    scale = scenario.get("demand_scale", 1.0)
    flows = []
    c = meta["corridor"]
    main = d["main_veh_per_hour_per_direction"] * scale
    for tag, ins, outs in (("nb", c["nb_entries"], c["nb_exits"]), ("sb", c["sb_entries"], c["sb_exits"])):
        if ins and outs:
            flows.append({"id": f"main_{tag}", "from": ins[0], "to": outs[-1], "veh_per_hour": main})
    exits = c["nb_exits"] + c["sb_exits"]
    for i, e in enumerate(meta["side_entry_edges"]):
        flows.append({"id": f"side_{i}", "from": e, "to": exits[i % len(exits)] if exits else e,
                      "veh_per_hour": d["side_veh_per_hour_per_approach"] * scale})
    p = SIM / "demand" / f"{scenario['name']}.rou.xml"
    p.parent.mkdir(parents=True, exist_ok=True)
    sr.write_flows(p, flows, 0, cfg["warmup_s"] + cfg["evaluation_s"])
    return str(p)


def scenarios(meta: dict) -> list[dict]:
    sc = _scfg()
    c = meta["corridor"]
    inc_edge = (c["northbound"] or c["southbound"] or [None])[len(c["northbound"]) // 2 if c["northbound"] else 0]
    cfg = settings.load("simulation")["simulation"]
    base = {"corridor_edges": c["northbound"] + c["southbound"], "side_prefix": "side_",
            "corridor_phase": meta["corridor_phase"]}
    return [
        {**base, "name": "routine_peak", "demand_scale": 1.0, "incident": None, "forecast_congested": False,
         "description": "routine PM-peak demand (declared from ATR medians where available)"},
        {**base, "name": "event_surge", "demand_scale": sc["event_demand_scale"], "incident": None,
         "forecast_congested": True, "description": f"STRESS SCENARIO: planned-event demand surge x{sc['event_demand_scale']} (configured, not observed)"},
        {**base, "name": "incident_reduced_capacity", "demand_scale": sc["event_demand_scale"],
         "incident": {"edge": inc_edge, "start": cfg["warmup_s"] + 300, "end": cfg["warmup_s"] + 1500, "speed_mps": 2.5,
                      "restore_mps": 13.9},
         "forecast_congested": True,
         "description": "STRESS SCENARIO: configured collision-like capacity reduction (speed cap 2.5 m/s for 20 min) plus surge"},
    ]


def paired_candidate_eval(meta: dict, scenario: dict, candidate: dict, seeds: list[int]) -> dict:
    """Matched-seed comparison candidate vs fixed-time baseline on one scenario."""
    net = settings.ROOT / meta["network"]["static"]
    routes = build_routes(meta, scenario)
    base, cand = [], []
    for s in seeds:
        base.append(sr.run_scenario(net, routes, scenario, "fixed_time", s))
        cand.append(sr.run_scenario(net, routes, scenario, "candidate", s, candidate=candidate))
    ok = [i for i in range(len(seeds)) if base[i]["status"] == "OK" and cand[i]["status"] == "OK"]
    def mean(rs, k):
        vals = [rs[i]["metrics"].get(k) for i in ok if rs[i]["metrics"].get(k) is not None]
        return float(np.mean(vals)) if vals else None
    bl, cl = mean(base, "corridor_mean_time_loss_s"), mean(cand, "corridor_mean_time_loss_s")
    bs, cs = mean(base, "side_road_mean_time_loss_s"), mean(cand, "side_road_mean_time_loss_s")
    return {"candidate_id": candidate["candidate_id"], "scenario": scenario["name"], "seeds_completed": len(ok),
            "status": "OK" if ok else "ERROR", "error": None if ok else (cand[0].get("error") or base[0].get("error")),
            "baseline_corridor_time_loss_s": bl, "candidate_corridor_time_loss_s": cl,
            "delay_improvement_pct": None if not bl or cl is None else round(100 * (bl - cl) / bl, 2),
            "side_road_delay_change_pct": None if not bs or cs is None else round(100 * (cs - bs) / bs, 2),
            "teleports_candidate": int(sum(cand[i]["metrics"]["teleports"] for i in ok)) if ok else 0,
            "control_log": [c["control_log"] for c in cand], "sim_run_ids": [r["run_id"] for r in base + cand],
            "pedestrian_protection": "NOT_EVALUATED"}


def evaluate_controllers(seeds: list[int] | None = None) -> list[dict]:
    """Fixed-time vs actuated vs deterministic forecast-informed rule on all scenarios, matched seeds."""
    meta = read_json(SIM / "scenarios" / "prepared.json")
    seeds = seeds or settings.load("simulation")["simulation"]["seeds"]
    rows = []
    write_json(SIM / "scenarios" / "scenarios.json", scenarios(meta))
    for scen in scenarios(meta):
        routes = build_routes(meta, scen)
        for ctrl in ("fixed_time", "actuated", "forecast_rule"):
            net = settings.ROOT / meta["network"]["actuated" if ctrl == "actuated" else "static"]
            for s in seeds:
                r = sr.run_scenario(net, routes, scen, ctrl, s)
                rows.append(r)
    return rows


def export_sim_rows(rows: list[dict], path=None):
    path = path or settings.ROOT / "reports" / "experiments" / "simulation_metrics.csv"
    path.parent.mkdir(parents=True, exist_ok=True)
    keys = sorted({k for r in rows for k in r["metrics"]})
    with open(path, "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["run_id", "mode", "scenario", "controller", "seed", "status", "error", "sumo_version", "network_hash",
                    "demand_hash", "warmup_s", "evaluation_s", "pedestrian_protection", *keys])
        for r in rows:
            w.writerow([r["run_id"], r["mode"], r["scenario"], r["controller"], r["seed"], r["status"], r["error"],
                        r["sumo_version"], r["network_hash"], r["demand_hash"], r["warmup_s"], r["evaluation_s"],
                        r["pedestrian_protection"], *[r["metrics"].get(k) for k in keys]])
    return path
