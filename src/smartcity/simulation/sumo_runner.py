"""SUMO + TraCI scenario-based microscopic simulation testbed.

Terminology (claim discipline): "scenario-based microscopic simulation testbed using real-world road geometry
(OpenStreetMap) and declared demand assumptions".  It is NOT a calibrated digital twin.  Signal programs are
generated by netconvert (``--tls.guess-signals``) and need not match real NYC timing plans.  All outputs are
labelled mode=SIMULATION.
"""

from __future__ import annotations

import hashlib
import os
import subprocess
import time
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np

from smartcity import settings
from smartcity.utils import new_run_id, write_json

SIM = settings.ROOT / "simulation"


def sumo_home() -> str:
    import sumo

    os.environ.setdefault("SUMO_HOME", sumo.SUMO_HOME)
    return sumo.SUMO_HOME


def binary(name: str = "sumo") -> str:
    env = os.environ.get("SUMO_BINARY") if name == "sumo" else None
    if env:
        return env
    return str(Path(sumo_home()) / "bin" / name)


def sumo_version() -> str:
    out = subprocess.run([binary(), "--version"], capture_output=True, text=True).stdout
    return out.splitlines()[0].strip() if out else "unknown"


def netconvert(osm: Path, out: Path, tls_type: str = "static", turn_lanes: bool = True) -> Path:
    # --osm.turn-lanes turns OSM turn:lanes tags into hard lane restrictions. On West St it makes a shared lane on the
    # 45 m link south of Chambers St right-turn-only, so through traffic must change lanes within 45 m and the merge
    # blocks the Chambers St junction (testbed audit, 2026-10-21); without it that lane also carries through traffic
    cmd = [binary("netconvert"), "--osm-files", str(osm), "--output-file", str(out),
           "--geometry.remove", "--ramps.guess", "--junctions.join", "--tls.guess-signals", "--tls.discard-simple",
           "--tls.join", "--tls.default-type", tls_type, "--keep-edges.by-vclass", "passenger",
           "--remove-edges.isolated", *(["--osm.turn-lanes"] if turn_lanes else []), "--no-turnarounds.tls", "--tls.yellow.time", "3",
           "--tls.allred.time", "2", "--seed", "42", "--no-warnings",
           "--output.street-names"]  # keep OSM names: corridor detection matches on edge names (dropped by default)
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"netconvert failed: {r.stderr[-2000:]}")
    return out


def tls_inventory(net_file: Path) -> dict:
    import sumolib

    net = sumolib.net.readNet(str(net_file), withPrograms=True)
    inv = {}
    for tls in net.getTrafficLights():
        progs = tls.getPrograms()
        entry = {"programs": list(progs.keys()), "phases": [], "controlled_edges": sorted(
            {c[0].getEdge().getID() for c in tls.getConnections()})}
        prog = next(iter(progs.values()))
        for i, ph in enumerate(prog.getPhases()):
            st = ph.state
            entry["phases"].append({"index": i, "duration": float(ph.duration), "state": st,
                                    "green": ("G" in st or "g" in st) and "y" not in st.lower().replace("g", ""),
                                    "minDur": float(getattr(ph, "minDur", ph.duration) or ph.duration),
                                    "maxDur": float(getattr(ph, "maxDur", ph.duration) or ph.duration)})
        inv[tls.getID()] = entry
    return inv


def write_flows(path: Path, flows: list[dict], begin: int, end: int):
    root = ET.Element("routes")
    ET.SubElement(root, "vType", id="car", accel="2.6", decel="4.5", sigma="0.5", length="5", minGap="2.5",
                  maxSpeed="20")
    for f in flows:
        # with an explicit route SUMO keeps it; a bare from/to flow is routed at insertion on current travel times
        ends = {} if f.get("route") else {"from": f["from"], "to": f["to"]}
        fl = ET.SubElement(root, "flow", id=f["id"], type="car", begin=str(begin), end=str(end),
                           vehsPerHour=f"{f['veh_per_hour']:.1f}", departLane="best", departSpeed="max", **ends)
        if f.get("route"):
            ET.SubElement(fl, "route", edges=" ".join(f["route"]))
    ET.ElementTree(root).write(path, encoding="utf-8", xml_declaration=True)
    return path


def file_hash(p: Path) -> str:
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()[:16]


class ProtectedController:
    """The only path through which a candidate touches a signal: re-validates the action against the live
    program (green phase exists, bounds, min/max green) before calling TraCI.  Clearance phases are never
    modified.  Raw state strings are never accepted."""

    def __init__(self, traci_mod, min_green: float, max_green: float, max_ext: float):
        self.traci, self.min_g, self.max_g, self.max_ext = traci_mod, min_green, max_green, max_ext
        self.log: list[dict] = []

    def extend_green(self, tls_id: str, phase_index: int, ext: float) -> bool:
        tl = self.traci.trafficlight
        if tls_id not in tl.getIDList():
            self.log.append({"tls": tls_id, "refused": "unknown tls"})
            return False
        active = tl.getProgram(tls_id)  # with a re-timed program loaded, the first logic is not the running one
        logic = next((lg for lg in tl.getAllProgramLogics(tls_id) if lg.programID == active),
                     tl.getAllProgramLogics(tls_id)[0])
        phases = list(logic.phases)
        if not (0 <= phase_index < len(phases)):
            self.log.append({"tls": tls_id, "refused": f"phase {phase_index} missing"})
            return False
        ph = phases[phase_index]
        st = ph.state
        if "y" in st or not ("G" in st or "g" in st):
            self.log.append({"tls": tls_id, "refused": "not a green phase"})
            return False
        if not (0 <= ext <= self.max_ext):
            self.log.append({"tls": tls_id, "refused": f"extension {ext} out of bounds"})
            return False
        new = ph.duration + ext
        if new < self.min_g or new > self.max_g:
            self.log.append({"tls": tls_id, "refused": f"duration {new} outside [{self.min_g},{self.max_g}]"})
            return False
        ph.duration = new
        if hasattr(ph, "minDur"):
            ph.minDur = new
        if hasattr(ph, "maxDur"):
            ph.maxDur = new
        logic.phases = tuple(phases)
        tl.setProgramLogic(tls_id, logic)
        self.log.append({"tls": tls_id, "phase": phase_index, "new_duration": new, "applied": True})
        return True


def run_scenario(net_file: Path, route_file: Path, scenario: dict, controller: str, seed: int,
                 candidate: dict | None = None, out_dir: Path | None = None, timeout_s: float = 900) -> dict:
    """Run one SUMO simulation through TraCI and return paired-comparison metrics.

    scenario: {name, corridor_edges, side_edges_prefix, incident: {edge, start, end, speed_mps}|None,
               forecast_congested: bool, corridor_phase: {tls_id: phase_index}}
    controller in {fixed_time, actuated, forecast_rule, candidate}
    """
    import traci

    cfg = settings.load("simulation")["simulation"]
    run_id = new_run_id(f"sim-{scenario['name']}-{controller}-s{seed}")
    out_dir = out_dir or (SIM / "outputs" / run_id)
    out_dir.mkdir(parents=True, exist_ok=True)
    tripinfo = out_dir / "tripinfo.xml"
    summary = out_dir / "summary.xml"
    end = cfg["warmup_s"] + cfg["evaluation_s"]
    cmd = [binary(), "-n", str(net_file), "-r", str(route_file), "--seed", str(seed), "--begin", "0",
           "--end", str(end + 1800), "--step-length", str(cfg["step_length_s"]), "--tripinfo-output", str(tripinfo),
           "--summary-output", str(summary), "--time-to-teleport", "300", "--no-step-log", "true",
           "--duration-log.disable", "true", "--no-warnings", "true", "--max-depart-delay", "900"]
    timing, adds = None, []
    if scenario.get("tls_additional") and controller != "actuated":  # the actuated baseline keeps its own programs
        adds.append(str(settings.ROOT / scenario["tls_additional"]))
        kind = scenario.get("signal_timing_kind", "webster_retimed")
        timing = f"{kind}:{file_hash(settings.ROOT / scenario['tls_additional'])}"
    adds += [str(settings.ROOT / a) for a in scenario.get("extra_additionals", [])]  # e.g. edgeData outputs
    if adds:
        cmd += ["-a", ",".join(adds)]
    label = run_id
    t0 = time.time()
    status, err = "OK", None
    queue_samples, applied = [], []
    teleports = 0
    corridor_lanes = []
    try:
        traci.start(cmd, label=label)
        conn = traci.getConnection(label)
        pc = ProtectedController(conn, cfg["min_green_s"], cfg["max_green_s"],
                                 settings.load("agents")["actions"]["green_extension_s"]["max"])
        for e in scenario.get("corridor_edges", []):
            try:
                corridor_lanes += [f"{e}_{i}" for i in range(conn.edge.getLaneNumber(e))]
            except Exception:
                pass
        acted = False
        inc = scenario.get("incident")
        step = 0
        while True:
            t = conn.simulation.getTime()
            if t >= end and conn.simulation.getMinExpectedNumber() == 0:
                break
            if t >= end + 1800:
                break
            if time.time() - t0 > timeout_s:
                status, err = "TIMEOUT", f"wall-clock timeout {timeout_s}s"
                break
            if not acted and t >= cfg["warmup_s"]:
                acted = True
                if controller == "forecast_rule" and scenario.get("forecast_congested"):
                    for tls_id, ph in scenario.get("corridor_phase", {}).items():
                        applied.append(pc.extend_green(tls_id, ph, 5.0))
                elif controller == "candidate" and candidate and candidate.get("action_type") == "bounded_green_extension":
                    applied.append(pc.extend_green(candidate["traffic_light_id"], int(candidate["phase_index"]),
                                                   float(candidate["extension_seconds"])))
            if inc:
                if inc["start"] <= t < inc["start"] + 1 and inc.get("edge"):
                    for i in range(conn.edge.getLaneNumber(inc["edge"])):
                        conn.lane.setMaxSpeed(f"{inc['edge']}_{i}", inc["speed_mps"])
                if inc["end"] <= t < inc["end"] + 1 and inc.get("edge"):
                    for i in range(conn.edge.getLaneNumber(inc["edge"])):
                        conn.lane.setMaxSpeed(f"{inc['edge']}_{i}", inc.get("restore_mps", 13.9))
            conn.simulationStep()
            teleports += conn.simulation.getStartingTeleportNumber()
            if t >= cfg["warmup_s"] and step % 10 == 0 and corridor_lanes:
                queue_samples.append(sum(conn.lane.getLastStepHaltingNumber(ln) for ln in corridor_lanes))
            step += 1
        loaded = conn.simulation.getLoadedNumber()  # in last step only; use summary instead
        pending = len(conn.simulation.getPendingVehicles())
        running = conn.vehicle.getIDCount()
        conn.close()
    except Exception as exc:
        status, err = "ERROR", f"{type(exc).__name__}: {exc}"[:500]
        try:
            traci.getConnection(label).close()
        except Exception:
            pass
        pending = running = None
    runtime = time.time() - t0
    metrics = parse_outputs(tripinfo, summary, cfg["warmup_s"], scenario.get("side_prefix", "side_"))
    metrics.update(teleports=teleports, mean_corridor_queue_veh=float(np.mean(queue_samples)) if queue_samples else None,
                   max_corridor_queue_veh=float(np.max(queue_samples)) if queue_samples else None,
                   pending_insertions_at_end=pending, running_at_end=running, wall_time_s=round(runtime, 2),
                   pedestrian_waiting_s=None)  # no pedestrian demand modelled -> NOT_EVALUATED
    res = {"run_id": run_id, "mode": "SIMULATION", "scenario": scenario["name"], "controller": controller, "seed": seed,
           "metrics": metrics, "sumo_version": sumo_version(), "network_hash": file_hash(net_file),
           "demand_hash": file_hash(route_file), "status": status, "error": err, "control_log": applied,
           "candidate": candidate, "demand": scenario.get("demand"), "signal_timing": timing, "warmup_s": cfg["warmup_s"], "evaluation_s": cfg["evaluation_s"],
           "pedestrian_protection": "NOT_EVALUATED (no pedestrian demand in scenario)"}
    write_json(out_dir / "result.json", res)
    return res


def parse_outputs(tripinfo: Path, summary: Path, warmup: float, side_prefix: str) -> dict:
    m: dict = {}
    if tripinfo.exists():
        trips = []
        for _, el in ET.iterparse(tripinfo, events=("end",)):
            if el.tag == "tripinfo":
                trips.append((el.get("id"), float(el.get("depart")), float(el.get("duration")),
                              float(el.get("timeLoss")), float(el.get("waitingTime")), int(el.get("waitingCount"))))
                el.clear()
        ev = [t for t in trips if t[1] >= warmup]
        side = [t for t in ev if t[0].startswith(side_prefix)]
        main = [t for t in ev if not t[0].startswith(side_prefix)]
        f = lambda xs, i: float(np.mean([x[i] for x in xs])) if xs else None  # noqa: E731
        m.update(completed_trips=len(ev), mean_travel_time_s=f(ev, 2), mean_time_loss_s=f(ev, 3),
                 mean_waiting_time_s=f(ev, 4), mean_stops=f(ev, 5), corridor_mean_time_loss_s=f(main, 3),
                 side_road_mean_time_loss_s=f(side, 3), side_road_trips=len(side))
    if summary.exists():
        last = None
        for _, el in ET.iterparse(summary, events=("end",)):
            if el.tag == "step":
                last = dict(el.attrib)
                el.clear()
        if last:
            m.update(loaded=int(float(last.get("loaded", 0))), inserted=int(float(last.get("inserted", 0))),
                     arrived=int(float(last.get("arrived", 0))), waiting_to_insert=int(float(last.get("waiting", 0))),
                     unfinished_trips=int(float(last.get("loaded", 0))) - int(float(last.get("arrived", 0))))
    return m
